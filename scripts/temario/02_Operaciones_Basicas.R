# Script 02_Operaciones_Basicas.r

a <- 9
b <- 2

# Operaciones Aritméticas
suma <- a + b      # Suma
resta <- a - b     # Resta
producto <- a * b  # Multiplicación
cociente <- a / b  # División
potencia <- a ^ b  # Potencia

# Operaciones de comparación
es_igual <- a == b   # FALSE
es_mayor <- a > b    # TRUE

# Operaciones lógicas
bandera <- es_igual & es_mayor  # FALSE

