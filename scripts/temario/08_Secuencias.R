# Función seq()
seq(1, 10)                  # equivalente a seq(from=1, to=10)
seq(10, 1, by=-2)           # equivalente a seq(from=10, to=1, by=-2)
seq(length=5, from=0, to=1) # equivalente a seq(0,1,length=5)

# Función rep()
rep(4,5)                    # equivalente a rep(x=4, times=5)
rep(x=c(1, 2, 3), times=3)  # equivalente a rep(c(1, 2, 3), 3)
rep(c(1, 2, 3), each=3)  

